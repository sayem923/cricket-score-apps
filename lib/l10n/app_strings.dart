  /// Returns the translation for [key] in the currently active language,
  /// falling back to English (then to the key itself) if a translation
  /// is missing, so a typo or an untranslated key never crashes the UI.
  static String tr(String key) {
    final entry = _translations[key];
    if (entry == null) return key;
    return entry[LocaleService.locale.value] ?? entry['en'] ?? key;
  }
